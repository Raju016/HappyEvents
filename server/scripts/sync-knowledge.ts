/**
 * Regenerates src/services/aura/siteKnowledge.generated.ts from the website's
 * own content (client/src/data/mockData.ts), so Aura answers from what the
 * site actually shows. Run after changing services or event categories:
 *
 *   npm run sync:knowledge
 */
import fs from 'fs';
import path from 'path';
import { EVENT_CATEGORIES, SERVICES } from '../../client/src/data/mockData';

const clean = (v: unknown) => String(v ?? '').replace(/\s+/g, ' ').trim();

const knowledge = {
  eventCategories: EVENT_CATEGORIES.map((c) => ({
    name: clean(c.name),
    tagline: clean(c.tagline),
    description: clean(c.description),
  })),
  services: SERVICES.map((s) => ({
    name: clean(s.name),
    summary: clean(s.shortDescription),
    features: (s.features || []).map(clean),
  })),
};

const out = path.resolve(__dirname, '../src/services/aura/siteKnowledge.generated.ts');
const body = `// AUTO-GENERATED by scripts/sync-knowledge.ts from client/src/data/mockData.ts.
// Do not edit by hand. Run: npm run sync:knowledge
export interface SiteKnowledge {
  eventCategories: { name: string; tagline: string; description: string }[];
  services: { name: string; summary: string; features: string[] }[];
}

export const SITE_KNOWLEDGE: SiteKnowledge = ${JSON.stringify(knowledge, null, 2)};
`;
fs.writeFileSync(out, body);
console.log(
  `Wrote ${knowledge.eventCategories.length} event categories and ${knowledge.services.length} services to ${out}`
);
